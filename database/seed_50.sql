-- ============================================================
-- Time_entry (1000 records)
-- Generated for assignments 1-50, distributed across work dates
-- ============================================================

-- Generate time entries using a series
-- For better distribution, we'll create entries for each assignment
DO $$
DECLARE
    i INT;
    v_assignment_id INT;
    v_work_date DATE;
    v_hours DOUBLE PRECISION;
    v_comment TEXT;
    v_comments TEXT[] := ARRAY[
        'Работа над задачей',
        'Анализ требований',
        'Разработка функционала',
        'Тестирование',
        'Исправление багов',
        'Код-ревью',
        'Встреча с командой',
        'Документирование',
        'Рефакторинг кода',
        'Интеграционные работы',
        'Настройка окружения',
        'Деплой на тестовый стенд',
        'Обсуждение архитектуры',
        'Оптимизация производительности',
        'Написание тестов',
        'Подготовка отчета',
        'Консультация заказчика',
        'Исследование решения',
        'Прототипирование',
        'Финальная проверка'
    ];
    v_hours_options DOUBLE PRECISION[] := ARRAY[1.0, 1.5, 2.0, 2.5, 3.0, 3.5, 4.0, 4.5, 5.0, 5.5, 6.0, 6.5, 7.0, 7.5, 8.0];
BEGIN
    FOR i IN 1..1000 LOOP
        -- Assign to one of the 50 assignments (cycling)
        v_assignment_id := ((i - 1) % 50) + 1;

        -- Generate work date based on assignment ranges
        -- Using deterministic dates based on entry number
        v_work_date := DATE '2023-01-10' + (i % 500);

        -- Select hours (deterministic based on i)
        v_hours := v_hours_options[((i - 1) % 15) + 1];

        -- Select comment (deterministic based on i)
        v_comment := v_comments[((i - 1) % 20) + 1];

        INSERT INTO Time_entry (assignment_id, work_date, hours, comment)
        VALUES (v_assignment_id, v_work_date, v_hours, v_comment);
    END LOOP;
END $$;

